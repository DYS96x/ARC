export function createTestTemplate(
  input: ModuleTemplateInput,
): string {
  const functionName = createFunctionName(input.title);

  return `import assert from "node:assert/strict";
import test from "node:test";
import { execute${functionName} } from "../service";

test("${input.slug} module returns a successful result", () => {
  const result = execute${functionName}({
    action: "test",
  });

  assert.equal(result.success, true);
});
`;
}