export type ModuleTemplateInput = {
  slug: string;
  identifier: string;
  title: string;
};

function createFunctionName(title: string): string {
  return title.replaceAll(" ", "");
}

export function createTypesTemplate(
  input: ModuleTemplateInput,
): string {
  return `export type ${input.identifier}ModuleInput = {
  action: string;
};

export type ${input.identifier}ModuleResult = {
  success: boolean;
  message: string;
};
`;
}

export function createConfigTemplate(
  input: ModuleTemplateInput,
): string {
  return `export const ${input.identifier}ModuleConfig = {
  name: "${input.slug}",
  title: "${input.title}",
  enabled: true,
  version: "0.1.0",
  maturity: "Seed",
} as const;
`;
}

export function createValidatorTemplate(
  input: ModuleTemplateInput,
): string {
  const functionName = createFunctionName(input.title);

  return `import type { ${input.identifier}ModuleInput } from "./types";

export function validate${functionName}Input(
  input: ${input.identifier}ModuleInput,
): string[] {
  const errors: string[] = [];

  if (!input.action.trim()) {
    errors.push("Action is required.");
  }

  return errors;
}
`;
}

export function createTemplatesTemplate(): string {
  return `export function createModuleDocument(
  title: string,
): string {
  return \`# \${title}

Generated by HOLY ARC.
\`;
}
`;
}

export function createServiceTemplate(
  input: ModuleTemplateInput,
): string {
  const functionName = createFunctionName(input.title);
  const typeName = `${input.identifier}Module`;
  const eventName = `${input.slug
    .toUpperCase()
    .replaceAll("-", "_")}_ACTION`;

  return `import { writeAuditEvent } from "../../infrastructure/logging";
import type {
  ${typeName}Input,
  ${typeName}Result,
} from "./types";

export function execute${functionName}(
  input: ${typeName}Input,
): ${typeName}Result {
  writeAuditEvent({
    event: "${eventName}",
    module: "${input.slug}",
    status: "INFO",
    metadata: {
      action: input.action,
    },
  });

  return {
    success: true,
    message: "${input.title} action completed.",
  };
}
`;
}

export function createCommandTemplate(
  input: ModuleTemplateInput,
): string {
  const functionName = createFunctionName(input.title);

  return `import { execute${functionName} } from "./service";

export function run${functionName}Command(
  args: string[],
): void {
  const action = args[0]?.trim();

  if (!action) {
    console.error("Usage: arc ${input.slug} <action>");
    process.exitCode = 1;
    return;
  }

  try {
    const result = execute${functionName}({
      action,
    });

    console.log(result.message);
  } catch (error) {
    const message =
      error instanceof Error
        ? error.message
        : "Unknown ${input.title} module error.";

    console.error(message);
    process.exitCode = 1;
  }
}
`;
}

export function createIndexTemplate(
  input: ModuleTemplateInput,
): string {
  const functionName = createFunctionName(input.title);

  return `export { run${functionName}Command } from "./command";
export { execute${functionName} } from "./service";
export type {
  ${input.identifier}ModuleInput,
  ${input.identifier}ModuleResult,
} from "./types";
`;
}

